#!/usr/bin/env node
// Density core vendoring: SDK -> ui-bridge-headless.
//
// The canonical density core lives in `packages/ui-bridge/src/density/` (pure:
// no DOM, no Node builtin, no build-time constant) with the `Observation`
// envelope it answers in at `packages/ui-bridge/src/observation/observation.ts`.
// `@qontinui/ui-bridge-headless` ships the `ui-bridge-density` command and
// cannot import the core from `@qontinui/ui-bridge`: the SDK already depends on
// headless (an optional peer, and a dynamic import in server/handlers.ts), so
// the edge would be a cycle, and headless builds BEFORE the SDK. So headless
// carries a GENERATED copy of every source file, imported by relative path.
//
//   node scripts/sync-density.mjs          write the copies (and delete stale ones)
//   node scripts/sync-density.mjs --check  exit 1 on any drift, missing copy or stale copy
//   (any other argument exits 2, so a typo never runs the writing sync)
//
// Sources: every `.ts` file directly in packages/ui-bridge/src/density/ (not
// `__tests__/`, and no `*.test.ts`), plus packages/ui-bridge/src/observation/observation.ts.
// Targets: the same names under packages/ui-bridge-headless/src/density/ and
// packages/ui-bridge-headless/src/observation/. Each copy is the source behind
// an `@generated` header, the idiom of scripts/sync-observation.mjs.
//
// A source whose imports reach outside the allowed set is REFUSED (exit 1 in
// both modes): a density file may import only a sibling (`./x`) or
// `../observation/observation`; the envelope may import nothing. A bare
// specifier, any other relative path, a `node:` builtin, a dynamic `import()`
// and a `require()` are all refused, because the copy must compile and run in
// headless with nothing but itself. So are a triple-slash reference directive
// and a file that does not parse. Imports are read from TypeScript's own parse
// of the file, never from a hand-written lexer.
//
// The writing sync deletes a stale copy only when it carries this script's
// `@generated` header; a hand-written file in a target directory is refused.
//
// The functions are exported so scripts/sync-density.test.mjs can drive them on
// fixture trees; the script acts only when invoked directly.
//
// Plan: 2026-11-23-ui-bridge-measures-information-density-as-reach-per-role-and-plans-the-change, Phase 2 (D-A).

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
// TypeScript parses each source, so the import scan never has to tell a regex
// from a division or a template from code (the root devDependency; CI runs
// `npm ci` before this script).
import ts from 'typescript';

const DEFAULT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Repo-relative (POSIX) locations of the two source sets and their targets. */
export const DENSITY_SOURCE_DIR = 'packages/ui-bridge/src/density';
export const OBSERVATION_SOURCE = 'packages/ui-bridge/src/observation/observation.ts';
export const DENSITY_TARGET_DIR = 'packages/ui-bridge-headless/src/density';
export const OBSERVATION_TARGET_DIR = 'packages/ui-bridge-headless/src/observation';

/** The one relative specifier a density file may use outside its siblings. */
const ENVELOPE_SPECIFIER = '../observation/observation';

const posix = (p) => p.split(sep).join('/');

/** The first bytes of every copy this script writes. */
const GENERATED_MARK = '// @generated by scripts/sync-density.mjs from ';

/** The `@generated` header written above each copy. */
export function generatedHeader(sourceRel) {
  return (
    `${GENERATED_MARK}${sourceRel} — do not edit.\n` +
    '// Edit the canonical file, then run `npm run density:sync`; CI runs\n' +
    '// `npm run density:check` and fails on any drift.\n\n'
  );
}

/** The CommonJS loader names; a vendored file may not refer to either. */
const LOADER_NAMES = new Set(['require', 'module']);

/** The names under which code can reach the global object. */
const GLOBAL_OBJECTS = new Set(['globalThis', 'global', 'window', 'self']);

/** `globalThis.require`, `global.module`, `self['require']`, and the like. */
function isGlobalLoaderAccess(node) {
  let object;
  let name;
  if (ts.isPropertyAccessExpression(node)) {
    object = node.expression;
    name = node.name.text;
  } else if (
    ts.isElementAccessExpression(node) &&
    ts.isStringLiteralLike(node.argumentExpression)
  ) {
    object = node.expression;
    name = node.argumentExpression.text;
  } else {
    return false;
  }
  // `(globalThis as any).require`: look through parentheses and type casts.
  while (
    ts.isParenthesizedExpression(object) ||
    ts.isAsExpression(object) ||
    ts.isNonNullExpression(object) ||
    ts.isTypeAssertionExpression(object) ||
    ts.isSatisfiesExpression(object)
  ) {
    object = object.expression;
  }
  return ts.isIdentifier(object) && GLOBAL_OBJECTS.has(object.text) && LOADER_NAMES.has(name);
}

/**
 * Whether an identifier refers to a binding, rather than naming a property or
 * a declared member (`o.require`, `{ require: 1 }`, `interface I { module: x }`
 * name things that merely share the word).
 */
function isValueReference(id) {
  const p = id.parent;
  if (p === undefined) return true;
  if (ts.isPropertyAccessExpression(p) && p.name === id) return false;
  if (ts.isQualifiedName(p) && p.right === id) return false;
  if (
    (ts.isPropertyAssignment(p) ||
      ts.isPropertySignature(p) ||
      ts.isPropertyDeclaration(p) ||
      ts.isMethodDeclaration(p) ||
      ts.isMethodSignature(p) ||
      ts.isGetAccessorDeclaration(p) ||
      ts.isSetAccessorDeclaration(p) ||
      ts.isEnumMember(p)) &&
    p.name === id
  ) {
    return false;
  }
  if (ts.isBindingElement(p) && p.propertyName === id) return false;
  return true;
}

/**
 * Every module edge in `text`, read from TypeScript's own parse of it (the
 * root `typescript` devDependency), so a comment, a string, a template, a
 * regular expression or a division can never be mistaken for code or hide
 * code: `{ kind, specifier, line }`, where `kind` is
 *
 * - `static` — an `import … from '…'`, a side-effect `import '…'`, an
 *   `export … from '…'`, or an `import x = require('…')`;
 * - `dynamic` — an `import(…)` call;
 * - `require` — a `require(…)` call;
 * - `reference` — a triple-slash `reference` directive (types, a path, a lib),
 *   which pulls declarations in without an import;
 * - `unparseable` — the file has a syntax error, so what it imports cannot be
 *   read with certainty (`specifier` carries the parser's message).
 *
 * A dynamic import, a require and a reference have `specifier: null`: each is
 * refused whatever it names.
 */
export function moduleEdges(text, fileName = 'x.ts') {
  const edges = [];
  const sf = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const lineOf = (pos) => sf.getLineAndCharacterOfPosition(pos).line + 1;

  const { diagnostics = [] } = ts.transpileModule(text, {
    fileName,
    reportDiagnostics: true,
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.Latest },
  });
  for (const d of diagnostics) {
    edges.push({
      kind: 'unparseable',
      specifier: ts.flattenDiagnosticMessageText(d.messageText, ' '),
      line: d.start === undefined ? 1 : lineOf(d.start),
    });
  }
  for (const ref of [
    ...sf.referencedFiles,
    ...sf.typeReferenceDirectives,
    ...sf.libReferenceDirectives,
  ]) {
    edges.push({ kind: 'reference', specifier: null, line: lineOf(ref.pos) });
  }

  const visit = (node) => {
    if (
      (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) &&
      node.moduleSpecifier !== undefined &&
      ts.isStringLiteral(node.moduleSpecifier)
    ) {
      edges.push({
        kind: 'static',
        specifier: node.moduleSpecifier.text,
        line: lineOf(node.moduleSpecifier.getStart(sf)),
      });
    } else if (
      ts.isImportEqualsDeclaration(node) &&
      ts.isExternalModuleReference(node.moduleReference)
    ) {
      const expr = node.moduleReference.expression;
      edges.push({
        kind: 'static',
        specifier: ts.isStringLiteral(expr) ? expr.text : '<computed>',
        line: lineOf(node.getStart(sf)),
      });
    } else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
      edges.push({ kind: 'dynamic', specifier: null, line: lineOf(node.getStart(sf)) });
    } else if (isGlobalLoaderAccess(node)) {
      // `globalThis.require`, `global['module']`: the loader reached through
      // the global object rather than by its bare name.
      edges.push({ kind: 'require', specifier: null, line: lineOf(node.getStart(sf)) });
    } else if (ts.isIdentifier(node) && LOADER_NAMES.has(node.text) && isValueReference(node)) {
      // Any reference to `require` or `module` — a call, `require.resolve`,
      // `module.require`, or an alias (`const r = require`) — is a way to load
      // a module the copy cannot resolve, so the bare name is the edge.
      edges.push({ kind: 'require', specifier: null, line: lineOf(node.getStart(sf)) });
    } else if (ts.isImportTypeNode(node)) {
      // `type T = import('pkg').X`: a type-level module edge.
      const arg = node.argument;
      const spec =
        ts.isLiteralTypeNode(arg) && ts.isStringLiteral(arg.literal)
          ? arg.literal.text
          : '<computed>';
      edges.push({ kind: 'static', specifier: spec, line: lineOf(node.getStart(sf)) });
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
  return edges.sort((a, b) => a.line - b.line);
}

/**
 * Why each edge of a source is refused, as strings; `[]` when it is allowed.
 * `siblings` are the base names (no `.ts`) of the density sources; `isEnvelope`
 * marks observation.ts, which may import nothing at all.
 */
export function forbiddenImports(sourceRel, text, siblings, isEnvelope) {
  const problems = [];
  for (const edge of moduleEdges(text)) {
    const at = `${sourceRel}:${edge.line}`;
    if (edge.kind === 'dynamic') {
      problems.push(`${at}: a dynamic import() is not allowed in a vendored file`);
      continue;
    }
    if (edge.kind === 'unparseable') {
      problems.push(
        `${at}: the file does not parse (${edge.specifier}), so its imports cannot be read; it is refused`
      );
      continue;
    }
    if (edge.kind === 'reference') {
      problems.push(`${at}: a triple-slash reference directive is not allowed in a vendored file`);
      continue;
    }
    if (edge.kind === 'require') {
      problems.push(
        `${at}: require() is not allowed in a vendored file (nor any reference to the CommonJS loader names require or module, a local of that name included)`
      );
      continue;
    }
    const spec = edge.specifier;
    if (isEnvelope) {
      problems.push(`${at}: the Observation envelope must have zero imports (found '${spec}')`);
      continue;
    }
    if (spec === ENVELOPE_SPECIFIER) continue;
    // The same allowed set as the density core's ESLint `no-restricted-imports`
    // block in eslint.config.js, which is the authority: `./<lower-kebab>` with
    // no extension, naming an existing sibling.
    const sibling = /^\.\/([a-z-]+)$/.exec(spec);
    if (sibling && siblings.includes(sibling[1])) continue;
    if (spec.startsWith('node:')) {
      problems.push(`${at}: '${spec}' is a Node builtin; the density core is pure`);
    } else if (!spec.startsWith('.')) {
      problems.push(`${at}: '${spec}' is a bare specifier; the copy cannot resolve packages`);
    } else {
      problems.push(
        `${at}: '${spec}' is outside the allowed set (a sibling './x' or '${ENVELOPE_SPECIFIER}')`
      );
    }
  }
  return problems;
}

/**
 * An OS or editor file that git ignores and no commit carries (`.DS_Store`, a
 * vim swap or backup file): it is neither a source nor a copy, so a dev box
 * holding one must not fail the sync or the check that CI passes.
 */
function isLocalJunk(name) {
  if (name === '.DS_Store' || name === 'Thumbs.db' || name === 'desktop.ini') return true;
  // A vim swap file is `.<name>.sw?`; a backup file ends in `~`.
  return name.endsWith('~') || /^\..+\.sw[a-p]$/.test(name);
}

/** The density sources: every `.ts` file directly in the source dir, sorted. */
function densitySources(root) {
  const dir = join(root, DENSITY_SOURCE_DIR);
  const entries = readdirSync(dir, { withFileTypes: true }).filter((e) => !isLocalJunk(e.name));
  const files = entries.filter((e) => e.isFile());
  // A `.tsx`, `.mts`, `.js` or any other file here, or a subdirectory other
  // than `__tests__/`, would not be copied, so it is refused, never skipped.
  const other = [
    ...files.filter((e) => !e.name.endsWith('.ts')).map((e) => e.name),
    ...entries.filter((e) => !e.isFile() && e.name !== '__tests__').map((e) => `${e.name}/`),
  ];
  if (other.length > 0) {
    throw new Error(
      `density:sync refused — ${DENSITY_SOURCE_DIR} may hold only .ts sources (and __tests__/); found: ${other.sort().join(', ')}`
    );
  }
  return files
    .map((e) => e.name)
    .filter((n) => !/\.test\.ts$/.test(n))
    .sort();
}

/**
 * Every copy the generator emits: a Map from repo-relative target path to its
 * full text. Throws (listing every refused edge) when a source imports outside
 * the allowed set.
 */
export function expectedDensityCopies(root = DEFAULT_ROOT) {
  const names = densitySources(root);
  const siblings = names.map((n) => n.replace(/\.ts$/, ''));
  const plan = [
    ...names.map((n) => ({
      source: `${DENSITY_SOURCE_DIR}/${n}`,
      target: `${DENSITY_TARGET_DIR}/${n}`,
      isEnvelope: false,
    })),
    {
      source: OBSERVATION_SOURCE,
      target: `${OBSERVATION_TARGET_DIR}/observation.ts`,
      isEnvelope: true,
    },
  ];
  const copies = new Map();
  const problems = [];
  for (const p of plan) {
    const text = readFileSync(join(root, p.source), 'utf8');
    problems.push(...forbiddenImports(p.source, text, siblings, p.isEnvelope));
    copies.set(p.target, generatedHeader(p.source) + text);
  }
  if (problems.length > 0) {
    throw new Error(
      `density:sync refused — imports outside the allowed set:\n  ${problems.join('\n  ')}`
    );
  }
  return copies;
}

/** Every file now under the two target directories, repo-relative. */
function existingCopies(root) {
  const out = [];
  const walk = (abs) => {
    if (!existsSync(abs)) return;
    for (const e of readdirSync(abs, { withFileTypes: true }).filter((x) => !isLocalJunk(x.name))) {
      const p = join(abs, e.name);
      if (e.isDirectory()) walk(p);
      else out.push(posix(relative(root, p)));
    }
  };
  walk(join(root, DENSITY_TARGET_DIR));
  walk(join(root, OBSERVATION_TARGET_DIR));
  return out.sort();
}

/**
 * The drift between the copies on disk and what the generator emits:
 * `{ drifted, missing, stale }`, each a sorted list of repo-relative paths.
 * Throws when a source is refused (see {@link expectedDensityCopies}).
 */
export function checkDensityCopies(root = DEFAULT_ROOT) {
  const want = expectedDensityCopies(root);
  const drifted = [];
  const missing = [];
  for (const [target, text] of want) {
    const abs = join(root, target);
    if (!existsSync(abs)) missing.push(target);
    else if (readFileSync(abs, 'utf8') !== text) drifted.push(target);
  }
  const stale = existingCopies(root).filter((p) => !want.has(p));
  return { drifted: drifted.sort(), missing: missing.sort(), stale };
}

/** Whether a file under a target dir is one this generator wrote (its header). */
function isGenerated(root, rel) {
  return readFileSync(join(root, rel), 'utf8').startsWith(GENERATED_MARK);
}

/**
 * Write every copy and delete every stale one. Returns what it did. A stale
 * file deleted must carry this generator's `@generated` header; any other
 * file under a target directory is somebody's hand-written work, so the sync
 * refuses (throws) and touches nothing rather than delete it.
 */
export function syncDensityCopies(root = DEFAULT_ROOT) {
  const want = expectedDensityCopies(root);
  const stale = existingCopies(root).filter((p) => !want.has(p));
  const foreign = stale.filter((p) => !isGenerated(root, p));
  if (foreign.length > 0) {
    throw new Error(
      `density:sync refused — file(s) under the generated directories that this script did not write:\n  ${foreign.join('\n  ')}\nMove them out of packages/ui-bridge-headless/src/{density,observation}/ (those directories are generated).`
    );
  }
  for (const p of stale) rmSync(join(root, p));
  for (const [target, text] of want) {
    const abs = join(root, target);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
  }
  return { written: [...want.keys()].sort(), removed: stale };
}

/** The script's own behaviour; returns the exit code. */
export function main(argv, root = DEFAULT_ROOT, out = console) {
  const unknown = argv.filter((a) => a !== '--check');
  if (unknown.length > 0) {
    // A typo such as `--chek` must not silently run the WRITING sync.
    out.error(
      `ERROR: unknown argument(s): ${unknown.join(' ')}. Usage: sync-density.mjs [--check]`
    );
    return 2;
  }
  const check = argv.includes('--check');
  try {
    if (check) {
      const { drifted, missing, stale } = checkDensityCopies(root);
      const lines = [
        ...drifted.map((p) => `  drifted: ${p}`),
        ...missing.map((p) => `  missing: ${p}`),
        ...stale.map((p) => `  stale (no source): ${p}`),
      ];
      if (lines.length > 0) {
        out.error(
          `ERROR: the vendored density core in ui-bridge-headless has drifted from packages/ui-bridge/src:\n${lines.join('\n')}\n` +
            'Run `npm run density:sync` and commit the result.'
        );
        return 1;
      }
      out.log(
        'density:check OK — the headless copies match the canonical density core and envelope'
      );
      return 0;
    }
    const { written, removed } = syncDensityCopies(root);
    out.log(
      `density:sync wrote ${written.length} file(s)${removed.length ? `, removed ${removed.join(', ')}` : ''}`
    );
    return 0;
  } catch (err) {
    out.error(`ERROR: ${err instanceof Error ? err.message : String(err)}`);
    return 1;
  }
}

const invokedAsScript = (() => {
  try {
    return (
      process.argv[1] !== undefined &&
      realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
    );
  } catch {
    return false;
  }
})();
if (invokedAsScript) {
  process.exit(main(process.argv.slice(2)));
}

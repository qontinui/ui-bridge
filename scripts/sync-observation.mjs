#!/usr/bin/env node
// Observation envelope vendoring: core -> React Native.
//
// The canonical Observation envelope lives in
// `packages/ui-bridge/src/observation/observation.ts` (zero imports).
// `@qontinui/ui-bridge-native` cannot import it from `@qontinui/ui-bridge`:
// that package is only an OPTIONAL peer of native (making it a hard dependency
// would switch on native's try-wrapped `@qontinui/ui-bridge/specs` require and
// ship ~355 KB into every mobile bundle), and a subpath import would need Metro
// package-`exports` support (RN >= 0.79) while native supports RN >= 0.70.
// So native carries a VENDORED copy, generated from the canonical file by this
// script, and imported by relative path.
//
//   node scripts/sync-observation.mjs          write the vendored copy
//   node scripts/sync-observation.mjs --check  exit 1 if the copy has drifted
//
// Same idiom as `diagnostics:generate` / `diagnostics:check`: the copy is
// generated, committed, and CI fails when it is not what the generator emits.
// Plan 2026-09-20-ui-bridge-observations-distinguish-cannot-see-from-not-present-and-carry-provenance, Phase 3.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'packages', 'ui-bridge', 'src', 'observation', 'observation.ts');
const TARGET = join(ROOT, 'packages', 'ui-bridge-native', 'src', 'observation', 'observation.ts');

const HEADER =
  '// @generated by scripts/sync-observation.mjs from ' +
  'packages/ui-bridge/src/observation/observation.ts — do not edit.\n' +
  '// Edit the canonical file, then run `npm run observation:sync`; CI runs\n' +
  '// `npm run observation:check` and fails on any drift.\n\n';

function expected() {
  const source = readFileSync(SOURCE, 'utf8');
  // Any module edge at all: a static `import`, a re-`export … from` (one-line
  // or the closing `} from '…'` of a multi-line one), a dynamic `import(…)` or
  // a `require(…)`. Comments are stripped first so prose cannot trip it.
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  const MODULE_EDGE =
    /\b(import|require)\s*\(|^\s*import\s|^\s*(import|export)\b[^;\n]*\bfrom\s|^\s*\}\s*from\s/m;
  if (MODULE_EDGE.test(code)) {
    // The copy is imported by relative path from native, so the canonical
    // file must stay self-contained.
    throw new Error(`${relative(ROOT, SOURCE)} must have zero imports to be vendored`);
  }
  return HEADER + source;
}

const check = process.argv.includes('--check');
const want = expected();

if (check) {
  let have = null;
  try {
    have = readFileSync(TARGET, 'utf8');
  } catch {
    have = null;
  }
  if (have !== want) {
    console.error(
      `ERROR: ${relative(ROOT, TARGET)} has drifted from ${relative(ROOT, SOURCE)}.\n` +
        'Run `npm run observation:sync` and commit the result.'
    );
    process.exit(1);
  }
  console.log('observation:check OK — the native copy matches the canonical envelope');
} else {
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, want);
  console.log(`observation:sync wrote ${relative(ROOT, TARGET)}`);
}
